#!/usr/bin/env node
// Reproducible cut of the character-library turnaround sheets into transparent PNGs for the 'toon' style.
//   node tools/extract-toon-characters.mjs        (needs ImageMagick `convert` on PATH to decode the JPEGs)
// Input : assets/library/<id>/turnaround.jpeg (installed with `factory library install`, see assets.lock.json)
// Output: src/art/toon/library/*.png, src/art/toon/library-data.js (base64 PNGs, so the single-file web build needs no fetch),
//         src/art/toon/library/manifest.json (provenance, license, sha256 of inputs and outputs, crop boxes).
// Sheet layout (both sheets 2400x1792): FRONT view in the left half, SIDE view (facing left) in the right half, captions below y=1610.
// There is no back view in the library; the game derives "up" frames in code (src/art/toon/characters.js).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeImageFile, cutout, keepMainComponents, bbox, crop, resizeToHeight, encodePng, sha256 } from '../src/kits/library-sprites/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_H = 384, CAPTION_Y = 1610;
const ASSETS = [
  { id: 'super-colby.toon-turnaround', key: 'colby', splitX: 1200 },
  { id: 'perring-parkway-pete.toon-turnaround', key: 'pete', splitX: 1082 },
];
const outDir = join(root, 'src/art/toon/library');
mkdirSync(outDir, { recursive: true });
const lock = JSON.parse(readFileSync(join(root, 'assets.lock.json'), 'utf8'));
const manifest = { generator: 'tools/extract-toon-characters.mjs', license: 'CC0-1.0', author: 'bsommers', library: 'character-library', note: 'Derived from the CC0 character-library turnaround sheets (cropped, background removed, downscaled). Original art by the library author.', sprites: {} };
const data = {};
for (const a of ASSETS) {
  const dir = join(root, 'assets/library', a.id), srcFile = join(dir, 'turnaround.jpeg');
  const lockEntry = lock.assets.find((x) => x.id === a.id);
  const srcHash = sha256(readFileSync(srcFile));
  const want = lockEntry && lockEntry.files.find((f) => f.path === 'turnaround.jpeg');
  if (!want || want.sha256 !== srcHash) throw new Error(`${a.id}: turnaround.jpeg does not match assets.lock.json (run factory library verify)`);
  const img = decodeImageFile(srcFile);
  cutout(img, { tol: 30, fringe: 2 });
  for (let y = CAPTION_Y; y < img.h; y++) for (let x = 0; x < img.w; x++) img.rgba[(y * img.w + x) * 4 + 3] = 0;
  keepMainComponents(img, 0.03);
  for (const [view, r] of [['front', { x0: 0, y0: 0, x1: a.splitX, y1: img.h }], ['side', { x0: a.splitX, y0: 0, x1: img.w, y1: img.h }]]) {
    const bb = bbox(img, 8, r), c = resizeToHeight(crop(img, bb.x0, bb.y0, bb.x1, bb.y1), OUT_H), png = encodePng(c), name = `${a.key}_${view}`;
    writeFileSync(join(outDir, name + '.png'), png);
    data[name] = 'data:image/png;base64,' + png.toString('base64');
    manifest.sprites[name] = { asset: a.id, view, w: c.w, h: c.h, sourceSha256: srcHash, cropBox: bb, sha256: sha256(png), facing: view === 'side' ? 'left' : 'front' };
  }
}
writeFileSync(join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
const dims = Object.fromEntries(Object.entries(manifest.sprites).map(([k, v]) => [k, { w: v.w, h: v.h }]));
writeFileSync(join(root, 'src/art/toon/library-data.js'), `// GENERATED by tools/extract-toon-characters.mjs - do not edit. Source: CC0 character-library (see library/manifest.json).\nexport const DIMS = ${JSON.stringify(dims)};\nexport const DATA = ${JSON.stringify(data, null, 1)};\n`);
console.log('OK', Object.entries(dims).map(([k, v]) => `${k} ${v.w}x${v.h}`).join(', '));
